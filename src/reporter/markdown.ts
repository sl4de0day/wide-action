import { ScanResult, VulnerabilityFinding } from '../types.js';

export function formatSummaryComment(
  scanResult: ScanResult,
  failOn: string,
  isBlocked: boolean
): string {
  const { summary, findings, totalFilesScanned } = scanResult;

  const statusText = isBlocked
    ? `BLOCKED - ${findings.length} issue(s) detected at or above ${failOn} threshold`
    : findings.length === 0
    ? 'PASSED - No security vulnerabilities detected'
    : 'PASSED WITH WARNINGS - Issues found below failure threshold';

  const rows = [
    '## Wide Security Audit Summary',
    '',
    '<div data-wide-action="summary"></div>',
    '',
    `**Status:** ${statusText}`,
    '',
    `**Files Scanned:** ${totalFilesScanned}`,
    '',
    '| Severity | Count |',
    '| :--- | :--- |',
    `| CRITICAL | ${summary.critical} |`,
    `| HIGH | ${summary.high} |`,
    `| MEDIUM | ${summary.medium} |`,
    `| LOW | ${summary.low} |`,
    `| TOTAL | ${summary.total} |`,
    ''
  ];

  if (findings.length > 0) {
    rows.push('### Detected Findings');
    rows.push('');
    rows.push('| Severity | Category | CWE | File:Line | Remediation |');
    rows.push('| :--- | :--- | :--- | :--- | :--- |');

    for (const f of findings) {
      const loc = `\`${f.file}:${f.line}\``;
      const cwe = f.cwe || 'N/A';
      const rem = (f.remediation || 'N/A').replace(/\|/g, '\\|');
      rows.push(`| ${f.severity} | ${f.title} | ${cwe} | ${loc} | ${rem} |`);
    }

    rows.push('');
  }

  rows.push('---');
  rows.push('*Report generated by Wide Action (Wide Ecosystem)*');

  return rows.join('\n');
}

export function formatInlineComment(finding: VulnerabilityFinding): string {
  const lines = [
    `### Wide Security: [${finding.severity}] ${finding.title} (${finding.cwe || 'CWE'})`,
    '',
    `<div data-wide-action="finding" data-rule-id="${finding.ruleId}"></div>`,
    '',
    `**Description:** ${finding.description}`,
    ''
  ];

  if (finding.snippet) {
    lines.push('**Vulnerable Line:**');
    lines.push('```');
    lines.push(finding.snippet);
    lines.push('```');
    lines.push('');
  }

  lines.push('**Recommended Remediation:**');
  lines.push(finding.remediation || 'Apply input validation and secure coding practices.');
  lines.push('');
  lines.push('---');
  lines.push('*Wide Action Security Gate*');

  return lines.join('\n');
}
